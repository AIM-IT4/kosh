package com.amitjha.kosh.reports

import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.amitjha.kosh.model.Money
import com.amitjha.kosh.model.Paise
import com.amitjha.kosh.model.TxnType
import com.amitjha.kosh.repo.Report
import java.io.OutputStream
import java.time.LocalDate
import java.time.format.DateTimeFormatter
import java.util.Locale

/** Writes a [Report] as an A4 PDF, drawn on the phone; nothing leaves the device unless the user shares the file. */
object ReportPdf {

    private const val W = 595
    private const val H = 842
    private const val M = 40f
    private val DAY = DateTimeFormatter.ofPattern("d MMM yyyy", Locale.ENGLISH)
    private val SHORT = DateTimeFormatter.ofPattern("dd MMM", Locale.ENGLISH)
    private val MONTH = DateTimeFormatter.ofPattern("MMM yyyy", Locale.ENGLISH)
    private const val GREEN = 0xFF047857.toInt()
    private const val RED = 0xFFB91C1C.toInt()
    private const val GREY = 0xFF6B7280.toInt()
    private const val RULE = 0xFFE5E7EB.toInt()

    fun write(report: Report, out: OutputStream, generated: LocalDate = LocalDate.now()) {
        val doc = PdfDocument()
        try {
            Writer(doc).apply {
                title(report)
                text("Generated by Kosh on ${DAY.format(generated)}", size = 9f, color = GREY)
                gap(14f)

                val s = report.summary
                heading("Summary")
                pair("Income", money(s.income), GREEN)
                pair("Spending", money(s.expense), RED)
                pair("Saved", money(s.savings), if (s.savings >= 0) GREEN else RED)
                s.savingsRate?.let { pair("Savings rate", String.format(Locale.ENGLISH, "%.1f%%", it * 100), GREY) }
                pair("Transactions", s.transactionCount.toString(), GREY)
                gap(10f)

                if (report.months.size > 1) {
                    heading("Month by month")
                    row(listOf("Month", "Income", "Spending", "Saved"), bold = true)
                    report.months.forEach { m ->
                        row(listOf(MONTH.format(m.period.start), money(m.income), money(m.expense), money(m.savings)))
                    }
                    gap(10f)
                }

                if (s.byCategory.isNotEmpty()) {
                    heading("Spending by category")
                    row(listOf("Category", "Amount", "Share", "Count"), bold = true)
                    s.byCategory.take(20).forEach { c ->
                        row(listOf(c.category?.name ?: c.categoryKey, money(c.total), String.format(Locale.ENGLISH, "%.1f%%", c.share * 100), c.count.toString()))
                    }
                    gap(10f)
                }

                if (s.topMerchants.isNotEmpty()) {
                    heading("Top merchants")
                    row(listOf("Merchant", "Amount", "Payments", ""), bold = true)
                    s.topMerchants.forEach { row(listOf(it.merchant, money(it.total), it.count.toString(), "")) }
                    gap(10f)
                }

                if (report.lines.isNotEmpty()) {
                    heading("Transactions")
                    lineRow(listOf("Date", "Description", "Category", "Account", "Amount"), bold = true)
                    report.lines.forEach { l ->
                        val signed = if (l.type == TxnType.INCOME) "+" + money(l.amount) else "−" + money(l.amount)
                        lineRow(
                            listOf(SHORT.format(l.date), l.title, l.category, l.account, signed),
                            color = if (l.type == TxnType.INCOME) GREEN else Color.BLACK,
                        )
                    }
                }
                finish()
            }
            doc.writeTo(out)
        } finally {
            doc.close()
        }
    }

    private fun money(p: Paise) = Money.format(p, showPaise = false)

    private class Writer(private val doc: PdfDocument) {
        private var pageNo = 0
        private var page: PdfDocument.Page? = null
        private lateinit var canvas: Canvas
        private var y = 0f
        private val paint = Paint(Paint.ANTI_ALIAS_FLAG)

        init { newPage() }

        private fun newPage() {
            page?.let { doc.finishPage(it) }
            pageNo++
            val p = doc.startPage(PdfDocument.PageInfo.Builder(W, H, pageNo).create())
            page = p
            canvas = p.canvas
            y = M
            paint.reset(); paint.isAntiAlias = true
            paint.textSize = 8f; paint.color = GREY
            canvas.drawText("Kosh · page $pageNo", W - M - paint.measureText("Kosh · page $pageNo"), H - 20f, paint)
        }

        private fun ensure(height: Float) { if (y + height > H - M) newPage() }

        fun finish() { page?.let { doc.finishPage(it) }; page = null }

        fun title(r: Report) {
            style(20f, bold = true, color = Color.BLACK)
            ensure(26f); y += 20f
            canvas.drawText(r.title, M, y, paint)
            style(11f, bold = false, color = GREY)
            y += 16f
            canvas.drawText("${DAY.format(r.from)} – ${DAY.format(r.toExclusive.minusDays(1))}", M, y, paint)
            y += 8f
        }

        fun heading(t: String) {
            ensure(40f)
            y += 8f
            style(12f, bold = true, color = GREEN)
            y += 12f
            canvas.drawText(t.uppercase(Locale.ENGLISH), M, y, paint)
            y += 4f
            paint.color = RULE
            canvas.drawLine(M, y, W - M, y, paint)
            y += 4f
        }

        fun text(t: String, size: Float = 10f, color: Int = Color.BLACK) {
            style(size, bold = false, color = color)
            ensure(size + 4f); y += size + 2f
            canvas.drawText(t, M, y, paint)
        }

        fun gap(h: Float) { y += h }

        fun pair(label: String, value: String, color: Int) {
            ensure(16f); y += 15f
            style(10.5f, bold = false, color = Color.DKGRAY)
            canvas.drawText(label, M, y, paint)
            style(10.5f, bold = true, color = color)
            canvas.drawText(value, W - M - paint.measureText(value), y, paint)
        }

        /** Four columns: a wide first one and three right-aligned amounts. */
        fun row(cells: List<String>, bold: Boolean = false) {
            ensure(14f); y += 13f
            style(9.5f, bold = bold, color = if (bold) GREY else Color.BLACK)
            val right = listOf(W - M - 220f, W - M - 120f, W - M - 40f, W - M)
            canvas.drawText(fit(cells[0], 230f), M, y, paint)
            for (i in 1 until cells.size) {
                val t = cells[i]
                canvas.drawText(t, right[i] - paint.measureText(t), y, paint)
            }
        }

        /** Date, description, category, account and a right-aligned amount. */
        fun lineRow(cells: List<String>, bold: Boolean = false, color: Int = Color.BLACK) {
            ensure(13f); y += 12f
            style(8.5f, bold = bold, color = if (bold) GREY else Color.BLACK)
            canvas.drawText(cells[0], M, y, paint)
            canvas.drawText(fit(cells[1], 190f), M + 50f, y, paint)
            canvas.drawText(fit(cells[2], 100f), M + 250f, y, paint)
            canvas.drawText(fit(cells[3], 80f), M + 355f, y, paint)
            if (!bold) paint.color = color
            canvas.drawText(cells[4], W - M - paint.measureText(cells[4]), y, paint)
        }

        private fun fit(t: String, width: Float): String {
            if (paint.measureText(t) <= width) return t
            var s = t
            while (s.isNotEmpty() && paint.measureText("$s…") > width) s = s.dropLast(1)
            return "$s…"
        }

        private fun style(size: Float, bold: Boolean, color: Int) {
            paint.textSize = size
            paint.typeface = if (bold) Typeface.DEFAULT_BOLD else Typeface.DEFAULT
            paint.color = color
        }
    }
}
