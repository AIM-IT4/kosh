/**
 * App languages. Hindi covers the fixed text of shared components (screen titles, section headers, buttons, menu
 * rows, form labels and tabs); text that carries names or amounts stays as it is.
 */
enum class AppLanguage(val code: String, val title: String) {
    ENGLISH("en", "English"),
    HINDI("hi", "हिन्दी");

    fun translator(): (String) -> String = when (this) {
        ENGLISH -> { s -> s }
        HINDI -> { s -> Hindi.words[s] ?: s }
    }

    companion object {
        fun of(code: String?): AppLanguage = entries.firstOrNull { it.code == code } ?: ENGLISH
    }
}

